"""Donor-matching imputation (CPS-ASEC → ACS PUMS).

ACS PUMS lacks several variables that the SPM resource calculation
needs for full Census P60-280 fidelity:

* **MOOP** (medical out-of-pocket expenses) — needed to subtract from
  resources. Currently zeroed in :func:`tax_modeler.poverty.compute_spm_resources`.
* **Childcare expenses paid out-of-pocket** — distinct from childcare
  *subsidy* received.
* **Work-related transportation expenses** — small but published.
* **Disambiguated transfer income** — ACS bundles "other income" (OIP)
  whereas CPS-ASEC reports SNAP/TANF/SSI cleanly. Phase 4 take-up
  imputation fills this from administrative caseload, but a CPS donor
  match is the canonical alternative.

The framework here is the standard k-nearest-neighbor donor-match used
by TRIM3, the SPM Research File, and PolicyEngine US's "Enhanced CPS":

  1. Both donors (CPS-ASEC) and recipients (ACS) are projected to a
     common feature space via ``match_vars`` (age, family size,
     income tier, etc.).
  2. Each recipient finds its K nearest donors by scaled Euclidean
     distance.
  3. Donor variables are averaged across the K nearest, with optional
     stratification (e.g. nearest donors *within the same income tier*).

Phase 8 ships:

  * Generic :class:`DonorMatcher`.
  * MOOP imputation (:func:`impute_moop`) as the first concrete use
    case, with a small bundled synthetic CPS-style donor fixture.

Replace the bundled donor fixture with a real CPS-ASEC SPM Research
File slice when promoting to production. The API contract here
(``donors_df`` + ``match_vars`` + ``donor_vars``) is stable.
"""
from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

from tax_modeler.errors import ConfigError, DataValidationError, MissingDataError

_PACKAGE_ROOT = Path(__file__).resolve().parents[1]
# Phase 9a: real Hawaii CPS-ASEC slice (~2,575 person-records). Generated by
# ``scripts/build_cps_asec_slice.py``. Falls back to the synthetic donor CSV
# when the real parquet isn't present (CI on a fresh clone).
_REAL_CPS_HI_PARQUET = _PACKAGE_ROOT / "data" / "cps_donor" / "cps_asec_hawaii.parquet"
_DEFAULT_CPS_DONOR_CSV = _PACKAGE_ROOT / "data" / "cps_donor" / "cps_moop_donors.csv"


@dataclass
class DonorMatcher:
    """K-nearest-neighbor donor-matching imputation engine.

    Attributes
    ----------
    donors_df:
        Donor frame (e.g. CPS-ASEC sample). Must contain every column
        in ``match_vars`` and ``donor_vars``.
    match_vars:
        Numeric features used for distance computation. Each is
        z-score-normalized so heterogeneously-scaled features (age,
        income, household size) get equal weight by default.
    donor_vars:
        Columns whose donor values are imputed onto recipients.
    k:
        Number of nearest neighbors. Default 5 — TRIM3 standard.
    feature_weights:
        Optional ``{match_var -> weight}`` dict to up- or down-weight
        specific features in the distance metric. Default: equal.
    """

    donors_df: pd.DataFrame
    match_vars: Sequence[str]
    donor_vars: Sequence[str]
    k: int = 5
    feature_weights: Mapping[str, float] = field(default_factory=dict)

    def __post_init__(self) -> None:
        missing = [c for c in list(self.match_vars) + list(self.donor_vars)
                   if c not in self.donors_df.columns]
        if missing:
            raise DataValidationError(
                f"DonorMatcher: donors_df is missing columns: {missing}",
                missing_columns=missing,
            )
        if self.k < 1:
            raise ConfigError(f"DonorMatcher.k must be >= 1; got {self.k}")
        # Pre-compute z-score scaling on match_vars
        d = self.donors_df[list(self.match_vars)].astype(float).to_numpy()
        self._mean = d.mean(axis=0)
        self._std = np.where(d.std(axis=0) > 0, d.std(axis=0), 1.0)
        self._donor_features = (d - self._mean) / self._std
        # Apply feature weights
        weights = np.array([
            float(self.feature_weights.get(v, 1.0)) for v in self.match_vars
        ])
        self._donor_features = self._donor_features * weights
        self._weights = weights
        self._donor_values = self.donors_df[list(self.donor_vars)].astype(float).to_numpy()

    def impute(self, recipients_df: pd.DataFrame) -> pd.DataFrame:
        """Add ``donor_vars`` columns to ``recipients_df`` via k-NN matching.

        Returns a copy of ``recipients_df``. Existing columns of the
        same name are preserved (idempotent — call twice safely).
        """
        out = recipients_df.copy()
        missing = [c for c in self.match_vars if c not in out.columns]
        if missing:
            raise DataValidationError(
                f"impute(): recipients_df missing match_vars: {missing}",
                missing_columns=missing,
            )

        r = out[list(self.match_vars)].astype(float).to_numpy()
        r_features = ((r - self._mean) / self._std) * self._weights

        # Pairwise distances (recipients × donors). For ~50 recipients
        # and ~200 donors this is trivial; switch to sklearn KDTree if
        # the recipient frame ever exceeds ~10k rows.
        # Distance² = ||r_i - d_j||²
        # Expanded: ||r||² + ||d||² - 2·(r·d)
        donors = self._donor_features
        r_norms = (r_features ** 2).sum(axis=1, keepdims=True)
        d_norms = (donors ** 2).sum(axis=1)
        cross = r_features @ donors.T
        d2 = r_norms + d_norms - 2.0 * cross

        k = min(self.k, len(self.donors_df))
        nearest_idx = np.argpartition(d2, k - 1, axis=1)[:, :k]

        for j, var in enumerate(self.donor_vars):
            donor_col = self._donor_values[:, j]
            picked = donor_col[nearest_idx]    # (n_recipients, k)
            imputed = picked.mean(axis=1)
            target_col = f"{var}_imputed" if var in out.columns else var
            out[target_col] = imputed

        return out


