def _load_default_cps_donors() -> pd.DataFrame:
    """Load the default CPS-style donor frame.

    Preference order:
      1. **Real Hawaii CPS-ASEC slice** at ``data/cps_donor/cps_asec_hawaii.parquet``
         (built by ``scripts/build_cps_asec_slice.py``). Production-grade.
      2. **Synthetic donor CSV** at ``data/cps_donor/cps_moop_donors.csv``
         (built by ``tests/tax_modeler/fixtures/_build_cps_donor_fixture.py``).
         CI-compatible fallback when the real slice isn't present.
    """
    if _REAL_CPS_HI_PARQUET.exists():
        donors = pd.read_parquet(_REAL_CPS_HI_PARQUET)
        # Real CPS slice has the columns we need but the variable mapping
        # done in build_cps_asec_slice.py already renames to: age, hh_size,
        # income, moop, childcare_expense, work_expense, weight. The donor
        # columns used by impute_moop / impute_childcare_expense /
        # impute_work_expense look these up directly.
        return donors
    if _DEFAULT_CPS_DONOR_CSV.exists():
        return pd.read_csv(_DEFAULT_CPS_DONOR_CSV)
    raise MissingDataError(
        f"No CPS donor fixture found. Looked for:\n"
        f"  (1) real slice at {_REAL_CPS_HI_PARQUET} — generate via "
        "scripts/build_cps_asec_slice.py\n"
        f"  (2) synthetic CSV at {_DEFAULT_CPS_DONOR_CSV} — generate via "
        "tests/tax_modeler/fixtures/_build_cps_donor_fixture.py",
        path=_REAL_CPS_HI_PARQUET,
    )


def impute_moop(
    units: pd.DataFrame,
    *,
    donors_df: pd.DataFrame | None = None,
    k: int = 5,
    out_col: str = "moop_amount",
) -> pd.DataFrame:
    """Impute medical out-of-pocket (MOOP) onto tax units via CPS donor match.

    Match features (z-scored): primary age, household size, income.
    Donor variable: ``moop_amount`` from the CPS-ASEC SPM Research File
    (or the bundled synthetic donor fixture).

    Returns a copy of ``units`` with ``out_col`` populated. The new
    column can be passed to :func:`tax_modeler.poverty.compute_spm_resources`
    as ``moop_col=out_col`` to remove MOOP from SPM resources, removing
    the ~1-2 pp poverty undercount documented in the Phase 2 SPM module.
    """
    df = units.copy()
    # Build recipient match frame directly (avoid name conflict with the
    # existing ``income`` column on ``df``)
    is_joint = (df["filing_status"] == "married_filing_jointly").to_numpy()
    n_dep = df["num_dependents"].fillna(0).astype(int).to_numpy()
    age_arr = (
        df["primary_agep"].fillna(0).astype(float).to_numpy()
        if "primary_agep" in df.columns
        else np.full(len(df), 35.0)
    )
    rec_for_match = pd.DataFrame({
        "age": age_arr,
        "hh_size": 1 + is_joint.astype(int) + n_dep,
        "income": df["income"].fillna(0).astype(float).clip(lower=0).to_numpy(),
    }, index=df.index)

    donors = donors_df if donors_df is not None else _load_default_cps_donors()
    matcher = DonorMatcher(
        donors_df=donors,
        match_vars=("age", "hh_size", "income"),
        donor_vars=("moop",),
        k=k,
    )
    imputed = matcher.impute(rec_for_match)

    df[out_col] = imputed["moop"].clip(lower=0).to_numpy()
    return df


def _impute_via_donor_match(
    units: pd.DataFrame,
    *,
    donor_var: str,
    donors_df: pd.DataFrame | None,
    k: int,
    out_col: str,
) -> pd.DataFrame:
    """Internal helper: build the recipient match frame and run a single-var impute."""
    df = units.copy()
    is_joint = (df["filing_status"] == "married_filing_jointly").to_numpy()
    n_dep = df["num_dependents"].fillna(0).astype(int).to_numpy()
    age_arr = (
        df["primary_agep"].fillna(0).astype(float).to_numpy()
        if "primary_agep" in df.columns
        else np.full(len(df), 35.0)
    )
    rec_for_match = pd.DataFrame({
        "age": age_arr,
        "hh_size": 1 + is_joint.astype(int) + n_dep,
        "income": df["income"].fillna(0).astype(float).clip(lower=0).to_numpy(),
    }, index=df.index)
    donors = donors_df if donors_df is not None else _load_default_cps_donors()
    if donor_var not in donors.columns:
        raise DataValidationError(
            f"donors_df missing column {donor_var!r} (have: {list(donors.columns)})",
            missing_columns=[donor_var],
        )
    matcher = DonorMatcher(
        donors_df=donors,
        match_vars=("age", "hh_size", "income"),
        donor_vars=(donor_var,),
        k=k,
    )
    imputed = matcher.impute(rec_for_match)
    df[out_col] = imputed[donor_var].clip(lower=0).to_numpy()
    return df


def impute_childcare_expense(
    units: pd.DataFrame,
    *,
    donors_df: pd.DataFrame | None = None,
    k: int = 5,
    out_col: str = "childcare_expense_amount",
) -> pd.DataFrame:
    """Impute out-of-pocket childcare expense onto units via CPS donor match.

    Donor variable: CPS-ASEC ``SPM_CHILDCAREXPNS`` (renamed
    ``childcare_expense`` in :func:`scripts/build_cps_asec_slice.py`).
    Match features: primary age, household size, income.

    Note this is the *parent-paid* expense (subtracted from SPM resources),
    distinct from the *childcare subsidy received* (column
    ``childcare_amount`` populated by ``benefits.childcare``). When both
    are present, SPM resources subtract the expense and add the subsidy.
    """
    return _impute_via_donor_match(
        units, donor_var="childcare_expense",
        donors_df=donors_df, k=k, out_col=out_col,
    )


def impute_work_expense(
    units: pd.DataFrame,
    *,
    donors_df: pd.DataFrame | None = None,
    k: int = 5,
    out_col: str = "work_expense_amount",
) -> pd.DataFrame:
    """Impute work-related expense (commute, etc.) onto units via CPS donor match.

    Donor variable: CPS-ASEC ``SPM_CAPWKCCXPNS`` minus
    ``SPM_CHILDCAREXPNS`` (the residual work-only piece) — computed as
    ``work_expense`` in the bundled HI slice.
    """
    return _impute_via_donor_match(
        units, donor_var="work_expense",
        donors_df=donors_df, k=k, out_col=out_col,
    )


