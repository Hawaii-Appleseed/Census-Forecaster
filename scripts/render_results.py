"""Write the current Act 24 result tables into SB3125_CD1_FORECAST.md from runs/.

    python scripts/render_results.py            # rewrite the generated block in place
    python scripts/render_results.py --check    # exit 1 if the file would change

The block sits between ``<!-- generated:results start -->`` and
``<!-- generated:results end -->``. If the markers are missing the block is
inserted before the first dated ``## `` section (the newest changelog entry).
Everything outside the markers is hand-written prose and is never touched.

Inputs (all under ``runs/``, written by the model chain; ``scripts/publish.py``
reruns the chain and then this script):

* ``sb3125_cd2_enhanced/{enhanced,quintile}.csv``   ``chain/forecast_sb3125_enhanced.py --cd 2``
* ``act24_vs_pre_act46/decomposition.csv``          ``chain/forecast_act24_vs_pre_act46.py``
* ``working_family_credits/{revenue_by_year,poverty_ty2028}.csv``
                                                    ``chain/forecast_working_family_credits.py``

The output carries no render timestamp, so identical runs give identical bytes.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parent.parent
DOC = REPO / "SB3125_CD1_FORECAST.md"
RUNS = REPO / "runs"

START = "<!-- generated:results start -->"
END = "<!-- generated:results end -->"

ENHANCED = "sb3125_cd2_enhanced"
PRE_ACT46 = "act24_vs_pre_act46"
WFC = "working_family_credits"

_DATED_H2 = re.compile(
    r"^## .*\b(?:January|February|March|April|May|June|July|August|September|October"
    r"|November|December) \d{1,2}, \d{4}", re.M)

MINUS = "−"


# ---- formatting ------------------------------------------------------------

def money(v: float) -> str:
    """$81.3M / −$11.1M / $1,036.9M."""
    s = f"${abs(v):,.1f}M"
    return (MINUS + s) if round(v, 1) < 0 else s


def num(v: float, signed: bool = False) -> str:
    """Plain one-decimal number with a true minus; ``signed`` adds + to positives."""
    r = round(v, 1)
    if r < 0:
        return f"{MINUS}{abs(r):,.1f}"
    return f"+{r:,.1f}" if signed and r > 0 else f"{r:,.1f}"


def whole(v: float) -> str:
    r = round(v)
    return f"{MINUS}{abs(r):,}" if r < 0 else f"+{r:,}"


def bold(s: str, on: bool) -> str:
    return f"**{s}**" if on else s


def md_table(header: list[str], aligns: list[str], rows: list[list[str]]) -> str:
    sep = ["--:" if a == "r" else "---" for a in aligns]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(sep) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


# ---- loading ---------------------------------------------------------------

def _manifest(runs: Path, name: str) -> dict | None:
    from tax_modeler.runs import read_run_manifest
    try:
        return read_run_manifest(runs / name)
    except (FileNotFoundError, OSError):
        return None


def _csv(runs: Path, name: str, f: str) -> pd.DataFrame:
    return pd.read_csv(runs / name / f)


# ---- sections --------------------------------------------------------------

def provenance(runs: Path) -> str:
    parts = []
    for name, script in ((ENHANCED, "chain/forecast_sb3125_enhanced.py --cd 2"),
                         (PRE_ACT46, "chain/forecast_act24_vs_pre_act46.py"),
                         (WFC, "chain/forecast_working_family_credits.py")):
        m = _manifest(runs, name)
        if m:
            parts.append(f"`{m.get('script', script)}` (`runs/{name}/`, git `{m['git_sha']}`, "
                         f"{m['created_at']})")
        else:
            parts.append(f"`{script}` (`runs/{name}/`, no manifest)")
    return ("*Generated by `scripts/render_results.py` from `runs/`; do not hand-edit between "
            "the markers. Sources: " + "; ".join(parts) + ".*")


def scenario_table(enh: pd.DataFrame) -> str:
    scens = list(dict.fromkeys(enh["scenario"]))
    years = sorted(enh["tax_year"].unique())
    piv = enh.pivot(index="tax_year", columns="scenario", values="total_impact_$M")
    rows = [[str(y)] + [bold(money(piv.loc[y, s]), s == "MID") for s in scens] for y in years]
    rows.append([bold(f"{len(years)}-year total", True)]
                + [bold(money(piv[s].sum()), True) for s in scens])
    head = ["Tax Year"] + [bold(s, s == "MID") for s in scens]
    return ("**CD2 vs Act 46 baseline, post-behavioral ($M)**\n\n"
            + md_table(head, ["l"] + ["r"] * len(scens), rows))


def mid_decomposition(enh: pd.DataFrame) -> str:
    mid = enh[enh["scenario"] == "MID"].sort_values("tax_year")
    cols = [("Act 46 baseline", "act46_baseline_$M", False),
            ("Static bracket", "bracket_delta_static_$M", True),
            ("ETI / migration", "eti_response_$M", True),
            ("PTE shift", "pte_shift_$M", True),
            ("Bracket (post-behav.)", "bracket_delta_post_$M", True),
            ("REEC", "reec_savings_$M", True),
            ("CGEC", "cgec_savings_$M", True),
            ("TCRA", "tcra_savings_$M", True),
            ("Credit total", "credit_total_$M", True),
            ("Total", "total_impact_$M", True)]
    rows = []
    for _, r in mid.iterrows():
        rows.append([str(int(r["tax_year"]))]
                    + [bold(money(r[c]), c.startswith("total")) for _, c, _t in cols])
    n = len(mid)
    rows.append([bold(f"{n}-year", True)]
                + ["" if not tot else bold(money(mid[c].sum()), True)
                   for _, c, tot in cols])
    head = ["Tax Year"] + [bold(h, h == "Total") for h, _, _ in cols]
    return ("**MID by component ($M)**\n\n" + md_table(head, ["l"] + ["r"] * len(cols), rows))


def pre_act46(dec: pd.DataFrame) -> str:
    cols = [("A: Act 46 banked ≤2026", "A_act46_banked_by_2026"),
            ("B: Act 46 remaining", "B_act46_remaining_phaseins"),
            ("C: Act 24 increment", "C_act24_increment"),
            ("**TOTAL vs pre-Act-46**", "total_vs_pre_act46"),
            ("memo: vs frozen 2026", "memo_vs_frozen_2026")]
    dec = dec.sort_values("tax_year")
    rows = []
    for _, r in dec.iterrows():
        rows.append([str(int(r["tax_year"]))]
                    + [bold(num(r[c], c.startswith("C_")), c == "total_vs_pre_act46")
                       for _, c in cols])
    rows.append([bold(f"{len(dec)}-year", True)]
                + [bold(num(dec[c].sum(), c.startswith("C_")), True) for _, c in cols])
    return ("**Act 24 against pre-Act-46 (2017) law ($M)** "
            "(`chain/forecast_act24_vs_pre_act46.py`; column C ties to the static bracket change)\n\n"
            + md_table(["Tax Year"] + [h for h, _ in cols], ["l"] + ["r"] * len(cols), rows))


def quintile_table(q: pd.DataFrame, year: int) -> str:
    d = q[q["tax_year"] == year]
    rows = []
    for _, r in d.iterrows():
        rows.append([r["quintile"], bold(whole(r["avg_per_hh_total_change"]), True),
                     f"{'+' if r['total_change_$M'] >= 0 else MINUS}"
                     f"{abs(r['total_change_$M']):,.2f}",
                     f"{r['pct_pay_more']:.1f}%"])
    return (f"**Who pays (MID TY{year})**\n\n"
            + md_table(["Fifth", "Avg. total ($/household)", "Total $M", "% paying more"],
                       ["l", "r", "r", "r"], rows))


def working_family(rev: pd.DataFrame, pov: pd.DataFrame) -> str:
    fut = rev[rev["tax_year"] >= 2028].sort_values("tax_year")
    rows = [[str(int(r["tax_year"])), money(r["eitc_loss_$M"]), money(r["food_loss_$M"]),
             bold(money(r["total_loss_$M"]), True)] for _, r in fut.iterrows()]
    lo, hi = int(fut["tax_year"].min()), int(fut["tax_year"].max())
    rows.append([bold(f"TY{lo}–{str(hi)[2:]}", True),
                 bold(money(fut["eitc_loss_$M"].sum()), True),
                 bold(money(fut["food_loss_$M"].sum()), True),
                 bold(money(fut["total_loss_$M"].sum()), True)])
    out = ("**Working-family credits expiring after TY2027: revenue loss ($M)** "
           "(`chain/forecast_working_family_credits.py`)\n\n"
           + md_table(["TY", "EITC loss", "Food/excise loss", "**Total**"],
                      ["l", "r", "r", "r"], rows))
    if len(pov):
        p = pov.iloc[0]
        out += (f"\n\nPoverty (TY{int(p['tax_year'])}): {int(p['persons_into_poverty']):,} more "
                f"people ({int(p['children_into_poverty']):,} children), poverty gap "
                f"{money(p['poverty_gap_increase_$M'])}.")
    return out


def render_block(runs: Path = RUNS) -> str:
    enh = _csv(runs, ENHANCED, "enhanced.csv")
    q = _csv(runs, ENHANCED, "quintile.csv")
    dec = _csv(runs, PRE_ACT46, "decomposition.csv")
    rev = _csv(runs, WFC, "revenue_by_year.csv")
    pov = _csv(runs, WFC, "poverty_ty2028.csv")
    years = sorted(q["tax_year"].unique())
    qyears = [years[0], years[-1]] if len(years) > 1 else years
    sections = [
        "## Current results (generated)",
        provenance(runs),
        scenario_table(enh),
        mid_decomposition(enh),
        pre_act46(dec),
        *[quintile_table(q, int(y)) for y in qyears],
        working_family(rev, pov),
    ]
    return START + "\n" + "\n\n".join(sections) + "\n" + END


# ---- splice ----------------------------------------------------------------

def splice(text: str, block: str) -> str:
    if START in text and END in text:
        i, j = text.index(START), text.index(END) + len(END)
        return text[:i] + block + text[j:]
    m = _DATED_H2.search(text)
    if not m:
        raise SystemExit("no markers and no dated '## ' section to insert before")
    return text[:m.start()] + block + "\n\n---\n\n" + text[m.start():]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the doc would change; write nothing")
    ap.add_argument("--doc", type=Path, default=DOC)
    ap.add_argument("--runs", type=Path, default=RUNS)
    args = ap.parse_args(argv)

    old = args.doc.read_text(encoding="utf-8")
    new = splice(old, render_block(args.runs))
    if new == old:
        print(f"{args.doc.name}: generated results are current")
        return 0
    if args.check:
        print(f"{args.doc.name}: generated results are stale; run "
              "python scripts/render_results.py", file=sys.stderr)
        return 1
    args.doc.write_text(new, encoding="utf-8")
    print(f"{args.doc.name}: generated results updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
