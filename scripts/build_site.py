# HTML/CSS bars rather than SVG: an SVG scales its text with the chart, so
# labels legible on a desktop shrink to ~7px on a phone. Bars sized in percent
# keep the text at its CSS size at every width. Each chart is one role="img"
# with a full-sentence aria-label; the data is also in a table or the CSVs.
