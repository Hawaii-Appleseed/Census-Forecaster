"""Run Hawaii program caseloads through the existing market-signal screen.

Exploratory; writes only docs/data_source_tests/caseload-screen-tables.md.
Uses lab.markets.screen.run_screen unchanged (lags 3/6/12, BH q=0.10, sign
check, 2020 pass, disaster-control pass) with the pairs registered below.
The bundled macro_monthly.json / selected_signals.json are only read.

    uv run python scripts/caseload_screen.py
"""
from __future__ import annotations

import json
from pathlib import Path

from lab.markets import screen as S
from lab.scripts.run_market_screen import _fmt_candidate_row, load_monthly_targets

ROOT = Path(__file__).resolve().parents[1]
CASE = json.loads((ROOT / "data/caseloads/hi_caseloads_monthly.json").read_text())["series"]
DIS = json.loads(
    (ROOT / "packages/census_forecaster/src/census_forecaster/data/markets/hi_disasters.json"
     ).read_text())

# Pre-registered BEFORE looking at any result. Primary pair = caseload ->
# HI_UNEMPLOYMENT, sign +: layoffs raise SNAP/Medicaid applications, and the
# caseload is an administrative count that precedes the LAUS estimate being
# revised. The other Hawaii targets get no mechanism and are two-sided
# (exempt from the sign check), run only because "against the existing
# Hawaii targets" was the brief.
PREDICTORS = {"SNAP_PERSONS": "SNAP_HI_PERSONS",
              "MEDICAID_CHIP": "MEDICAID_CHIP_HI_TOTAL"}
TARGETS = ["HI_UNEMPLOYMENT", "HONOLULU_ZHVI", "HONOLULU_ZORI",
           "HI_ELECTRICITY", "HI_VISITORS", "HONOLULU_SF_MEDIAN"]
PAIRS = [(p, t) for p in PREDICTORS for t in TARGETS]
for p in PREDICTORS:
    S.EXPECTED_SIGN[(p, "HI_UNEMPLOYMENT")] = +1   # in-process only


def main() -> None:
    preds = {n: S.series_to_monthly_dict(CASE[k]) for n, k in PREDICTORS.items()}
    targets = load_monthly_targets()
    print("targets present:", sorted(targets))
    # Caseload-distortion windows: EA end (Mar 2023), Medicaid unwinding
    # (Apr 2023 - mid 2024), Maui fire + D-SNAP (Aug 2023 -): 2023-01..2024-12.
    distort = [f"{y}-{m:02d}" for y in (2023, 2024) for m in range(1, 13)]
    runs = {
        "Full sample": dict(),
        "2020 excluded": dict(exclude_2020=True),
        "Disaster control (hi_disasters.json candidate months)":
            dict(exclude_months=DIS["candidate_exclusion_months"]),
        "2020 + 2023-24 distortion windows excluded":
            dict(exclude_2020=True, exclude_months=distort),
    }
    reps = {k: S.run_screen(preds, targets, pairs=PAIRS, **kw)
            for k, kw in runs.items()}
    lines = ["# Caseload screen tables (generated by scripts/caseload_screen.py)", ""]
    summary = {}
    for name, rep in reps.items():
        lines += [f"## {name} - {rep.n_tests} Granger tests run "
                  f"({rep.excluded_months} months dropped by list)", "",
                  "| predictor | transform | target | lags | F | p | n | best xcorr | "
                  "sign | BH pass | note |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for c in rep.candidates:
            lines.append(_fmt_candidate_row(c))
        lines.append("")
        passes = [(c.ticker, c.target, c.lags) for c in rep.candidates if c.bh_pass]
        ps = sorted(c.granger.p_value for c in rep.candidates if c.granger)
        summary[name] = {"tests": rep.n_tests, "bh_pass": passes,
                         "smallest_p": [round(x, 4) for x in ps[:5]]}
    lines += ["## Primary pair sign detail (mean r over leads 1..lag; predicted +)", "",
              "| run | predictor | lag | mean r | materiality 1/sqrt(n) | verdict |",
              "|---|---|---|---|---|---|"]
    for name, rep in reps.items():
        for c in rep.candidates:
            if c.target == "HI_UNEMPLOYMENT" and c.lags and c.sign_stat is not None:
                n = c.granger.nobs if c.granger else None
                mat = f"{S.sign_materiality(n):.3f}" if n else "-"
                v = {None: "below materiality / no test", True: "ok", False: "WRONG"}[c.sign_ok]
                lines.append(f"| {name} | {c.ticker} | {c.lags} | {c.sign_stat:+.3f} | {mat} | {v} |")
    lines.append("")
    out = ROOT / "docs/data_source_tests/caseload-screen-tables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
